"""Build the requirement → test traceability matrix (brief §13).

Requirement IDs come from docs/spec/FUNCTIONAL_SPEC.md (pattern **AREA-NNN**). A test covers a
requirement when the ID appears in its name or description (Python test files under
engine/tests, TypeScript *.test.ts under packages/ and apps/). Tests must pass in the same CI
run; this script only checks references.

    uv run --project engine python scripts/trace.py [--phase N] [--out docs/dhf/TRACEABILITY.md]

With --phase N the script exits non-zero if any requirement whose area is delivered in a phase
≤ N has no referencing test.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs" / "spec" / "FUNCTIONAL_SPEC.md"
REQ_DEF = re.compile(r"\*\*([A-Z]+-\d{3})\*\*")
REQ_REF = re.compile(r"\b([A-Z]+)[-_](\d{3})\b")

# Phase in which each requirement area is delivered (brief §10, Phase 2 split per docs/PROMPT.md).
AREA_PHASE = {
    "GEN": 2, "DIR": 2, "SAFE": 2,
    "DSC": 3,
    "MM": 4, "REG": 4, "DIF": 4,
    "DCE": 5, "PERM": 5,
    "TRK": 6, "FMRI": 7, "MRS": 8, "LBA": 9,
    "ADV": 10, "SUB": 10, "ECHO": 10,
}  # fmt: skip


def requirements() -> list[str]:
    return list(dict.fromkeys(REQ_DEF.findall(SPEC.read_text(encoding="utf-8"))))


def test_files() -> list[Path]:
    files = list((ROOT / "engine" / "tests").rglob("test_*.py"))
    for base in ("packages", "apps"):
        d = ROOT / base
        if d.exists():
            files += [p for p in d.rglob("*.test.ts") if "node_modules" not in p.parts]
    return sorted(files)


def references(files: list[Path], known: set[str]) -> dict[str, set[str]]:
    refs: dict[str, set[str]] = defaultdict(set)
    for f in files:
        rel = f.relative_to(ROOT).as_posix()
        for area, num in REQ_REF.findall(f.read_text(encoding="utf-8")):
            rid = f"{area}-{num}"
            if rid in known:
                refs[rid].add(rel)
    return refs


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", type=int, default=None)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "dhf" / "TRACEABILITY.md")
    args = ap.parse_args()

    reqs = requirements()
    refs = references(test_files(), set(reqs))
    lines = [
        "# Traceability matrix",
        "",
        "Generated by `scripts/trace.py`; do not edit by hand.",
        "",
        "| Requirement | Phase | Tests |",
        "|---|---|---|",
    ]
    missing: list[str] = []
    for rid in reqs:
        phase = AREA_PHASE.get(rid.split("-")[0], 99)
        tests = sorted(refs.get(rid, ()))
        lines.append(f"| {rid} | {phase} | {'<br>'.join(tests) if tests else '—'} |")
        if args.phase is not None and phase <= args.phase and not tests:
            missing.append(rid)
    covered = sum(1 for r in reqs if refs.get(r))
    lines += ["", f"Coverage: {covered} of {len(reqs)} requirements referenced by at least one test."]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{covered}/{len(reqs)} requirements referenced; matrix written to {args.out.relative_to(ROOT)}")
    if missing:
        print(f"Missing tests for delivered requirements: {', '.join(missing)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
