// Export the NeuroMR-PRO design tokens (brief §3.6) from the design-system package
// (design/design-system/tokens.css, mirrored in Open Design as user:neuromr-pro) to the
// files application code consumes:
//   packages/ui/src/tokens/tokens.css   CSS custom properties (--nm-* only)
//   packages/ui/src/tokens/tokens.ts    typed values plus var() references
//   design/screens/assets/tokens.css    the same CSS for the exported design screens
// Usage: pnpm tokens            (write)
//        pnpm tokens --check    (exit 1 if the exported files are out of date)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "design/design-system/tokens.css");
const outCss = join(root, "packages/ui/src/tokens/tokens.css");
const outTs = join(root, "packages/ui/src/tokens/tokens.ts");
const outDesign = join(root, "design/screens/assets/tokens.css");

const css = readFileSync(source, "utf8");
const decls = [...css.matchAll(/^\s*(--nm-[a-z0-9-]+):\s*([^;]+);/gm)].map((m) => [m[1], m[2].trim()]);
if (decls.length === 0) throw new Error(`no --nm-* tokens found in ${source}`);

const header = "/* Generated by scripts/export-tokens.mjs from design/design-system/tokens.css. Do not edit. */\n";
const cssOut = `${header}:root {\n${decls.map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;

const camel = (name) => name.replace(/^--nm-/, "").replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const tsOut = `${header.replace("/*", "/**").replace(" */", "\n */")}
/** Resolved token values, keyed by camel-cased name without the --nm- prefix. */
export const tokens = {
${decls.map(([k, v]) => `  ${camel(k)}: ${JSON.stringify(v)},`).join("\n")}
} as const;

export type TokenName = keyof typeof tokens;

/** CSS custom-property names, for building style objects: \`{ color: cssVar.colorTextPrimary }\`. */
export const cssVar = {
${decls.map(([k]) => `  ${camel(k)}: "var(${k})",`).join("\n")}
} as const satisfies Record<TokenName, string>;

/** Text tokens and the surfaces they may sit on; every pair must reach 4.5:1 (brief §4.2). */
export const TEXT_TOKENS = ["colorTextPrimary", "colorTextSecondary", "colorTextTertiary"] as const;
export const SURFACE_TOKENS = ["colorBg", "colorSurface", "colorRaised", "colorHover"] as const;
`;

const targets = [
  [outCss, cssOut],
  [outTs, tsOut],
  [outDesign, cssOut],
];

if (process.argv.includes("--check")) {
  const stale = targets.filter(([p, c]) => !existsSync(p) || readFileSync(p, "utf8") !== c).map(([p]) => p);
  if (stale.length) {
    console.error(`tokens out of date, run pnpm tokens:\n${stale.join("\n")}`);
    process.exit(1);
  }
  console.log(`tokens up to date (${decls.length} tokens)`);
} else {
  for (const [p, c] of targets) {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, c);
  }
  console.log(`exported ${decls.length} tokens`);
}
